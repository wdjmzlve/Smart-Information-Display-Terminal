/**
 * @brief 取 ASCII 字符的 8x16 点阵
 * @param[in] ch 待查询字符
 * @return 16 字节字模指针；非 ASCII 可打印字符返回 NULL
 */
const uint8_t *screen_font_ascii_glyph(char ch)
{
    uint8_t code = (uint8_t)ch;

    if ((code < SCREEN_FONT_FIRST_CHAR) || (code > SCREEN_FONT_LAST_CHAR))
    {
        return NULL;
    }

    return s_font_ascii[code - SCREEN_FONT_FIRST_CHAR];
}
